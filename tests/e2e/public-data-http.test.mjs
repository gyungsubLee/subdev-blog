import test from 'node:test';
import assert from 'node:assert/strict';
import { publicRepository, A, ID, REPOSITORY } from '../support/public-repository.mjs';
import { createGitHubClient } from '../../app/server/src/github.mjs';
import { ensurePublicPublication } from '../../app/server/src/public-publication.mjs';

// A lost source-candidate response must be recoverable through real Git-shaped fixture objects.
test('GitHub fixture preserves source trees, blobs, parents and non-force refs across publication', async () => {
  const f=publicRepository();
  const client=createGitHubClient('test',f.fetcher);
  const call=(path,options)=>client('/repos/'+REPOSITORY+path,options);
  const blob=await call('/git/blobs',{method:'POST',body:{content:Buffer.from('attachment').toString('base64'),encoding:'base64'}});
  const source=f.commits.get(A);
  const tree=await call('/git/trees',{method:'POST',body:{base_tree:source.tree.sha,tree:[{path:`posts/${ID}/file.txt`,mode:'100644',type:'blob',sha:blob.sha}]}});
  assert.ok(f.trees.get(tree.sha).some(entry=>entry.path==='categories.json'));
  const candidate=await call('/git/commits',{method:'POST',body:{message:'test',tree:tree.sha,parents:[A]}});
  assert.equal(f.commits.get(candidate.sha).parents[0].sha,A);
  await ensurePublicPublication({commit:candidate.sha,repository:REPOSITORY,github:call,fetcher:f.fetcher});
  await call('/git/refs/heads/main',{method:'PATCH',body:{sha:candidate.sha,force:false}});
  assert.equal(f.refs.get('main'),candidate.sha);
  assert.ok(f.refs.has('public-data/'+candidate.sha));
  await assert.rejects(call('/git/refs/heads/main',{method:'PATCH',body:{sha:A,force:false}}),error=>error.status===422);
});

import { createPublicE2EServer } from '../support/public-e2e-server.mjs';
import { randomUUID } from 'node:crypto';
import { runPublicPublication } from '../../app/content/scripts/publish-public-content.mjs';

test('HTTP E2E: authentication, generated reads, CRUD, retry, category save and push generation', {timeout:60000}, async t => {
  const app=await createPublicE2EServer();
  t.after(()=>app.close());
  const origin=app.origin;
  const unauthorized=await fetch(origin+'/api/content',{method:'POST',body:'{}'});
  assert.equal(unauthorized.status,401);
  const login=await fetch(origin+'/__e2e/login',{redirect:'manual'});
  const cookie=login.headers.get('set-cookie').split(';')[0];
  const request=async (pathname,input)=>{
    const response=await fetch(origin+'/api/'+pathname,{method:input?'POST':'GET',headers:{cookie,origin,'x-csrf-token':'e2e-csrf','Content-Type':'application/json'},body:input?JSON.stringify(input):undefined});
    return {status:response.status,data:await response.json()};
  };
  const session=await request('session');
  assert.equal(session.data.state,'ready');
  const deniedCsrf=await fetch(origin+'/api/content',{method:'POST',headers:{cookie,origin,'x-csrf-token':'wrong','Content-Type':'application/json'},body:'{}'});
  assert.equal(deniedCsrf.status,403);
  const initial=await request('public?kind=index');
  assert.equal(initial.status,200);
  assert.equal(initial.data.posts.length,1);
  assert.equal(initial.data.posts[0].bodyLoaded,false);
  const detail=await request(`public?kind=post&id=${ID}&commit=${initial.data.contentCommit}`);
  assert.equal(detail.data.markdown,'Original body');
  const id=randomUUID();
  const create={requestId:randomUUID(),baseCommit:initial.data.contentCommit,operation:{type:'post.create',document:{metadata:{schema_version:1,id,title:'E2E HTTP',parent_id:null,created:'2026-11-04',updated:'2026-11-04',private_note:'never-public'},markdown:'# Created\n\nHTTP E2E body'}}};
  const saved=await request('content',create);
  assert.equal(saved.status,200,JSON.stringify(saved.data));
  assert.equal(saved.data.state,'saved');
  const stillPrevious=await request('public?kind=index&after='+saved.data.contentCommit);
  assert.equal(stillPrevious.status,200);
  assert.equal(stillPrevious.data.contentCommit,initial.data.contentCommit);
  assert.equal((await request('publish?requestId='+create.requestId+'&candidateCommit='+saved.data.candidateCommit)).data.state,'saved');
  await runPublicPublication(['--commit',saved.data.contentCommit,'--publish'],{env:{},fetcher:app.gateway});
  assert.equal((await request('publish?requestId='+create.requestId+'&candidateCommit='+saved.data.candidateCommit)).data.state,'published');
  const retry=await request('content',create);
  assert.equal(retry.data.contentCommit,saved.data.contentCommit);
  const index=await request('public?kind=index&after='+saved.data.contentCommit);
  assert.equal(index.data.posts.length,2);
  assert.ok(!JSON.stringify(index.data).includes('never-public'));
  const source=await request('content?kind=post&id='+id);
  const update={requestId:randomUUID(),baseCommit:saved.data.contentCommit,operation:{type:'post.update',id,baseRevision:source.data.revision,changes:{title:'E2E Updated'},markdown:'# Updated\n\nUpdated body'}};
  const updated=await request('content',update);
  assert.equal(updated.status,200,JSON.stringify(updated.data));
  await runPublicPublication(['--commit',updated.data.contentCommit,'--publish'],{env:{},fetcher:app.gateway});
  const latest=await request('public?kind=index&after='+updated.data.contentCommit);
  assert.equal(latest.data.posts.find(post=>post.id===id).title,'E2E Updated');
  const updatedSource=await request('content?kind=post&id='+id);
  const deleted=await request('content',{requestId:randomUUID(),baseCommit:updated.data.contentCommit,operation:{type:'post.delete',id,baseRevision:updatedSource.data.revision}});
  assert.equal(deleted.status,200,JSON.stringify(deleted.data));
  await runPublicPublication(['--commit',deleted.data.contentCommit,'--publish'],{env:{},fetcher:app.gateway});
  const afterDelete=await request('public?kind=index&after='+deleted.data.contentCommit);
  assert.equal(afterDelete.data.posts.length,1);
  const categories=await request('content?kind=categories');
  const added=await request('content',{requestId:randomUUID(),baseCommit:deleted.data.contentCommit,operation:{type:'categories.save',baseRevision:categories.data.revision,categories:[...categories.data.categories,{id:'group:e2e',name:'E2E',parent_id:null,order:1,sources:[]}]}});
  assert.equal(added.status,200,JSON.stringify(added.data));
  await runPublicPublication(['--commit',added.data.contentCommit,'--publish'],{env:{},fetcher:app.gateway});
  const afterCategory=await request('public?kind=index&after='+added.data.contentCommit);
  assert.ok(afterCategory.data.categories.some(category=>category.id==='group:e2e'));
  const beforeFailure=app.f.refs.get('main');
  const original=await request('content?kind=post&id='+ID);
  const failPayload={requestId:randomUUID(),baseCommit:beforeFailure,operation:{type:'post.update',id:ID,baseRevision:original.data.revision,changes:{title:'Recovered'}}};
  app.f.controls.failPath='/git/ref/heads/public-data/';
  const failed=await request('content',failPayload);
  assert.equal(failed.status,200);
  assert.equal(failed.data.state,'saved');
  assert.equal(app.f.refs.get('main'),failed.data.contentCommit);
  await assert.rejects(runPublicPublication(['--commit',failed.data.contentCommit,'--publish'],{env:{},fetcher:app.gateway}));
  const duringFailure=await request('public?kind=index&after='+failed.data.contentCommit);
  assert.equal(duringFailure.status,200);
  assert.equal(duringFailure.data.contentCommit,beforeFailure);
  assert.ok(app.f.refs.has('cms/requests/'+failPayload.requestId),'Failed workflow retains source and its recovery candidate');
  app.f.controls.failPath='';
  const recovered=await request('content',failPayload);
  assert.equal(recovered.status,200,JSON.stringify(recovered.data));
  assert.equal(recovered.data.contentCommit,failed.data.contentCommit);
  await runPublicPublication(['--commit',recovered.data.contentCommit,'--publish'],{env:{},fetcher:app.gateway});
  // Simulate a direct source push. The same CLI used by the workflow creates its public ref.
  app.f.addSource('e'.repeat(40));
  app.f.commits.get('e'.repeat(40)).parents=[{sha:app.f.refs.get('main')}];
  app.f.refs.set('main','e'.repeat(40));
  const notReady=await request('public?kind=index&after='+'e'.repeat(40));
  assert.equal(notReady.status,200);
  assert.equal(notReady.data.contentCommit,recovered.data.contentCommit);
  await runPublicPublication(['--commit','e'.repeat(40),'--publish'],{env:{},fetcher:app.gateway});
  const pushed=await request('public?kind=index&after='+'e'.repeat(40));
  assert.equal(pushed.status,200);
  assert.equal(pushed.data.contentCommit,'e'.repeat(40));
  assert.equal((await request('logout',{})).data.state,'signed_out');
});

test('HTTP E2E serves exact pinned asset bytes and excludes editor sources', {timeout:15000}, async t => {
  const {document}=await import('../support/public-repository.mjs');
  const image=Buffer.from('89504e470d0a1a0a','hex');
  const app=await createPublicE2EServer({files:{[`posts/${ID}/Title.md`]:document('![image](./image.png)'),[`posts/${ID}/image.png`]:image,[`posts/${ID}/editor.json`]:'{}'}});
  t.after(()=>app.close());
  const index=await(await fetch(app.origin+'/api/public?kind=index')).json();
  const destination=index.posts[0].markdown.match(/\]\(([^)]+)\)/)[1];
  assert.ok(destination.startsWith(app.origin+'/__e2e/assets/'+A+'/'));
  const asset=await fetch(destination);
  assert.equal(asset.status,200);
  assert.equal(asset.headers.get('content-type'),'image/png');
  assert.ok(Buffer.from(await asset.arrayBuffer()).equals(image));
  assert.equal((await fetch(app.origin+`/__e2e/assets/${A}/posts/${ID}/editor.json`)).status,404);
});
